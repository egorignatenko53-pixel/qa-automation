package org.example;

public class Calculator {

    public int sum(int a, int b) {
        return a + b;
    }

    public boolean isPositive(int number) {
        return number > 0;
    }
    public int multiply(int a, int b) {
        return a * b;
    }
    public int divide(int a, int b) {
        return a / b;
    }
}